#!/usr/bin/env python3
"""Print the README security card from the built binary, so its numbers are measured.

Startup cost = characters of what an app loads at startup (instructions, tool definitions,
prompt list) divided by 4, the usual rule of thumb for English and JSON.
Usage: python3 scripts/security_card.py [--check] [--binary PATH]
--check exits 1 when the README card differs from the output (run in CI).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bench_probe import DEFAULT_BINARY, ROOT, Probe  # noqa: E402

NETWORK = "None. Bench makes no network calls and sends no telemetry."
FILES = ("Reads the skills folder beside the binary. Writes the approval log "
         "(`~/.local/state/bench/approvals.jsonl`, arguments redacted; `BENCH_APPROVAL_LOG` moves it). "
         "Tags only: `~/.bench/device-tags.json` (`tag_device`). Nothing else is written.")
SECRETS = "Bench stores no credentials and needs none. Its settings are environment variables only, and it never returns them to the model."


def card(binary: Path) -> str:
    probe = Probe(binary)
    try:
        tools = probe.request("tools/list")["tools"]
        prompts = probe.request("prompts/list")["prompts"]
        instructions = probe.server.get("instructions") or ""
    finally:
        probe.close()
    startup = instructions + json.dumps(tools, sort_keys=True) + json.dumps(prompts, sort_keys=True)
    ann = lambda t: t.get("annotations") or {}  # noqa: E731
    read_only = [t["name"] for t in tools if ann(t).get("readOnlyHint")]
    # destructiveHint marks exactly the approval-gated device writes (DeviceWrites in BenchCore).
    gated = [t["name"] for t in tools if ann(t).get("destructiveHint")]
    local = [t["name"] for t in tools if not ann(t).get("readOnlyHint") and not ann(t).get("destructiveHint")]
    return "\n".join([
        "<!-- security-card:start (generated by scripts/security_card.py) -->",
        "| Security card | |",
        "|---|---|",
        f"| Network | {NETWORK} |",
        f"| Files | {FILES} |",
        f"| Secrets | {SECRETS} |",
        f"| Read-only tools | {len(read_only)}: {', '.join(f'`{n}`' for n in read_only)} |",
        f"| Needs your approval | {len(gated)}: {', '.join(f'`{n}`' for n in gated)}. The client shows each call; the model's own `confirm` flag does not count. `hid_send` needs approval except for its read actions. |",
        f"| Changes without approval | {', '.join(f'`{n}`' for n in local)}: open or close a port, or change Bench's own tag and snapshot data. No device write. |",
        f"| Startup cost | about {round(len(startup) / 4, -2):,.0f} tokens ({len(tools)} tools, {len(prompts)} skill prompts) |",
        "| Changes | Tool and prompt text is locked by hash (`tool-manifest.lock.json`); CI fails if it changes without the lock. |",
        "<!-- security-card:end -->",
    ])


def main(argv: list[str]) -> int:
    binary = DEFAULT_BINARY
    if "--binary" in argv:
        binary = Path(argv[argv.index("--binary") + 1])
    text = card(binary)
    if "--check" in argv:
        readme = (ROOT / "README.md").read_text(encoding="utf-8")
        match = re.search(r"<!-- security-card:start.*?<!-- security-card:end -->", readme, re.S)
        ok = bool(match) and match.group(0) == text
        print("security card is current" if ok else "README security card is stale: run python3 scripts/security_card.py and paste it in")
        return 0 if ok else 1
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
